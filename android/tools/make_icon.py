#!/usr/bin/env python3
"""Writes the adaptive icon's glyph layer as an Android vector drawable.

The brand mark is the twelve rounded rectangles in public/favicon.svg (same data as
ios/tools/make_icon.swift). Adaptive icons are masked to a circle of 66dp inside a
108dp canvas, so the glyph is scaled to stay inside that safe zone.

    python3 tools/make_icon.py
"""
from pathlib import Path

RECTS = [
    (18.15, 0, 18.15, 18.15), (18.15, 36.3, 18.15, 36.3), (18.15, 90.74, 18.15, 18.15),
    (72.6, 0, 18.15, 18.15), (72.6, 36.3, 18.15, 36.3), (72.6, 90.74, 18.15, 18.15),
    (0, 18.15, 18.15, 18.15), (36.3, 18.15, 36.3, 18.15), (90.74, 18.15, 18.15, 18.15),
    (0, 72.6, 18.15, 18.15), (36.3, 72.6, 36.3, 18.15), (90.74, 72.6, 18.15, 18.15),
]
GLYPH = 108.89
RADIUS = 3.0
SCALE = 0.50  # farthest corner is ~33dp from the centre: inside the 66dp safe circle


def rounded(x, y, w, h, r=RADIUS):
    return (
        f"M{x + r:.2f},{y:.2f}H{x + w - r:.2f}A{r},{r} 0 0 1 {x + w:.2f},{y + r:.2f}"
        f"V{y + h - r:.2f}A{r},{r} 0 0 1 {x + w - r:.2f},{y + h:.2f}"
        f"H{x + r:.2f}A{r},{r} 0 0 1 {x:.2f},{y + h - r:.2f}"
        f"V{y + r:.2f}A{r},{r} 0 0 1 {x + r:.2f},{y:.2f}Z"
    )


path = "".join(rounded(*r) for r in RECTS)
offset = (108 - GLYPH * SCALE) / 2


def vector(color):
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/make_icon.py -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="{offset:.2f}" android:translateY="{offset:.2f}" android:scaleX="{SCALE}" android:scaleY="{SCALE}">
        <path android:fillColor="{color}" android:pathData="{path}" />
    </group>
</vector>
"""


drawable = Path(__file__).resolve().parent.parent / "app/src/main/res/drawable"
(drawable / "ic_launcher_foreground.xml").write_text(vector("#FF6333"))
# The themed icon (Android 13+) is tinted by the system, so it only needs the shape.
(drawable / "ic_launcher_monochrome.xml").write_text(vector("#FFFFFFFF"))
print("wrote", drawable)
